export type IconName = keyof typeof ICONS;

export function icon(name: IconName, size = 16) {
  const el = createElement(ICONS[name]);
  el.setAttribute("width", String(size));
  el.setAttribute("height", String(size));
  el.setAttribute("aria-hidden", "true");
  el.classList.add("icon");
  return el;
}

/** The raw SVG node list, for drawing an icon inside another SVG (the upgrade graph). */
export const iconNode = (name: IconName): IconNode => ICONS[name];
